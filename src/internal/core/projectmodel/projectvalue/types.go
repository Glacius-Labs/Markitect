// Package projectvalue owns pure project-model, exploration-binding, and
// repository-path values shared by the application and Host adapters.
// It performs no filesystem, Git, provider, or persistence operations.
package projectvalue

import (
	"github.com/Glacius-Labs/Markitect/src/internal/core"
	"github.com/Glacius-Labs/Markitect/src/internal/core/projectmodel"
	"github.com/Glacius-Labs/Markitect/src/internal/core/projectmodel/projectcoverage"
	"github.com/Glacius-Labs/Markitect/internal/tooling/source"
)

const (
	ManifestPath        = ".markitect/project.yaml"
	ModelRoot           = ".markitect/model"
	RuntimePath         = ".markitect/runtime.yaml"
	ViewPath            = ".markitect/views/project.md"
	DefaultDocumentPath = "docs/markitect/project.md"

	WorkflowModeGuided             = "guided"
	WorkflowModeEmpty              = "empty"
	AcceptancePolicyCommittedModel = "committed-model"
	HumanActor                     = "user"
	APIVersion                     = projectmodel.APIVersion

	// GeneratedViewMarker is the stable first-line marker for a generated
	// project document. Its literal is part of the existing overwrite guard.
	GeneratedViewMarker = "<!-- Generated by Markitect projectwork; edit selected model sources instead. -->"
)

type Exclusion struct {
	Path   string `json:"path" yaml:"path"`
	Reason string `json:"reason" yaml:"reason"`
}

type Config struct {
	DocumentPath string `json:"documentPath,omitempty" yaml:"documentPath,omitempty"`
	CoverageMode string `json:"coverageMode,omitempty" yaml:"coverageMode,omitempty"`
	WorkflowMode string `json:"workflowMode,omitempty" yaml:"workflowMode,omitempty"`
	// AcceptancePolicyCommittedModel treats canonical committed model YAML as
	// the accepted repository specification; draft files remain proposals.
	AcceptancePolicy       string      `json:"acceptancePolicy,omitempty" yaml:"acceptancePolicy,omitempty"`
	APIVersion             string      `json:"apiVersion" yaml:"apiVersion"`
	Name                   string      `json:"name" yaml:"name"`
	ModelFiles             []string    `json:"modelFiles" yaml:"modelFiles"`
	InventoryRoots         []string    `json:"inventoryRoots" yaml:"inventoryRoots"`
	Exclusions             []Exclusion `json:"exclusions" yaml:"exclusions"`
	TransitionalExclusions []Exclusion `json:"transitionalExclusions,omitempty" yaml:"transitionalExclusions,omitempty"`
}

type Project struct {
	Coverage    *projectcoverage.Report `json:"coverage,omitempty"`
	Root        string                  `json:"-"`
	Revision    string                  `json:"revision"`
	Provisional bool                    `json:"provisional"`
	Digest      string                  `json:"digest"`
	Config      Config                  `json:"config"`
	Model       core.Model              `json:"model"`
	Report      projectmodel.Report     `json:"report"`
	Snapshot    *source.Input      `json:"-"`
	// Census is the full repository census Load classified. It also holds
	// ignored, transitional and operational paths that Snapshot omits.
	Census *projectcoverage.Universe `json:"-"`
}

type FileChange struct {
	Path    string `json:"path"`
	Content string `json:"content"`
	Delete  bool   `json:"delete,omitempty"`
}

type Mutation struct {
	APIVersion string       `json:"apiVersion"`
	BaseDigest string       `json:"baseDigest"`
	Actor      string       `json:"actor"`
	Goal       string       `json:"goal"`
	Files      []FileChange `json:"files"`
}

type EditPlan struct {
	APIVersion      string                    `json:"apiVersion"`
	BaseDigest      string                    `json:"baseDigest"`
	Digest          string                    `json:"digest"`
	Mutation        Mutation                  `json:"mutation"`
	CandidateDigest string                    `json:"candidateDigest"`
	Report          projectmodel.Report       `json:"report"`
	Impact          projectmodel.ChangeImpact `json:"impact"`
}

// BasisFile binds source bytes which are not adequately represented by Git
// HEAD alone, such as project configuration, runtime configuration, or state.
type BasisFile struct {
	Path   string `json:"path"`
	Digest string `json:"digest"`
}

// Binding is supplied by the Host after it has loaded the exact fixed project
// model and computed the requested work-item scope. Plan identifiers are
// intentionally absent so this binding remains stable across plan creation.
type Binding struct {
	RepositoryRoot        string      `json:"repositoryRoot"`
	Branch                string      `json:"branch"`
	Head                  string      `json:"head"`
	ModelRevision         string      `json:"modelRevision"`
	ModelAccepted         bool        `json:"modelAccepted"`
	AcceptancePolicy      string      `json:"acceptancePolicy"`
	ProjectDigest         string      `json:"projectDigest"`
	ModelDigest           string      `json:"modelDigest"`
	SnapshotDigest        string      `json:"snapshotDigest"`
	SelectionDigest       string      `json:"selectionDigest"`
	RuntimeDigest         string      `json:"runtimeDigest,omitempty"`
	BriefingDigest        string      `json:"briefingDigest,omitempty"`
	ScopeID               string      `json:"scopeId"`
	ScopeName             string      `json:"scopeName"`
	Goal                  string      `json:"goal"`
	Operation             string      `json:"operation"`
	ManagerIDs            []string    `json:"managerIds"`
	ResponsibleManagerIDs []string    `json:"responsibleManagerIds"`
	RequiredArtifacts     []string    `json:"requiredArtifacts"`
	FileStructure         []string    `json:"fileStructure"`
	Checks                []string    `json:"checks"`
	BasisFiles            []BasisFile `json:"basisFiles"`
}
