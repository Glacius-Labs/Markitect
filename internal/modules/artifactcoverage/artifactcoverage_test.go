func TestCheckAccountsSuppliedOwnershipAndNewFiles(t *testing.T) {
	config, inventory := fixture()
	inventory.InputOwners = append(inventory.InputOwners, OwnerFact{Path: "content/reference.md", Owner: "general/Skill/another"})
	report, err := Check(config, inventory)
	if err != nil {
		t.Fatal(err)
	}
	if report.Status != "passed" || report.SnapshotDigest != inventory.SnapshotDigest {
		t.Fatalf("unexpected report: %#v", report)
	}
	for _, expected := range [][2]string{{"content/canonical.yaml", "canonical"}, {"content/reference.md", "input"}, {"generated/entry.md", "generated"}, {"tools/check.go", "tooling"}, {"content/retained.md", "excluded"}} {
		if !hasClass(report, expected[0], expected[1]) {
			t.Errorf("missing %s classification for %s", expected[1], expected[0])
		}
	}
	if got := strings.Join(ownersFor(report, "content/reference.md"), ","); got != "general/Rule/policy,general/Skill/another" {
		t.Fatalf("shared input consumers = %q", got)
	}
	if got := reasonFor(report, "content/retained.md"); got != "retained historical fixture" {
		t.Fatalf("exclusion reason = %q", got)
	}

	inventory.Files["content/new.md"] = []byte("new and unowned\n")
	report, err = Check(config, inventory)
	if err != nil {
		t.Fatal(err)
	}
	if !hasFinding(report, "unmanaged", "content/new.md") {
		t.Fatalf("new file was not reported: %#v", report.Findings)
	}
}

