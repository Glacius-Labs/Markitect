func TestSelectedPackageDomainGetsContractAndIndexEntry(t *testing.T) {
	d := core.ModelDomain{Name: "engineering-constitution-v1", APIVersion: "engineering.markitect.org/v1alpha1", Kinds: map[string]core.KindDefinition{"Workflow": {Properties: map[string]core.PropertyDefinition{"intent": {Type: "string"}}}}}
	input := core.ModelDomainInput{APIVersion: d.APIVersion, Name: d.Name, Path: "domains/software.yaml", Package: "engineering-constitution", PackageVersion: "1.0.0"}
	m := core.SemanticModel{Domains: []core.ModelDomain{d}, DomainInputs: []core.ModelDomainInput{input}}
	out, owners, err := Generate(m, Config{Enabled: true, ProjectKey: "Project/consumer"}, nil)
	if err != nil {
		t.Fatal(err)
	}
	contractPath := "docs/markitect/_domains/engineering.markitect.org.v1alpha1.domain.md"
	contract := string(out[contractPath])
	if !strings.Contains(contract, "<!-- Generated by Markitect; source: domains/software.yaml -->") || !strings.Contains(contract, "- **Definition source:** `domains/software.yaml`") {
		t.Fatalf("selected package Domain lost the source path from its normalized DomainInput:\n%s", contract)
	}
	index := string(out["docs/markitect/_domains/README.md"])
	if !strings.Contains(index, "engineering-constitution-v1") || !strings.Contains(index, "source `domains/software.yaml`") {
		t.Fatalf("selected package Domain is absent from its index:\n%s", index)
	}
	if got := strings.Join(owners[contractPath], ","); got != "domain:engineering.markitect.org/v1alpha1/engineering-constitution-v1" {
		t.Fatalf("package Domain contract owners = %q", got)
	}
}

