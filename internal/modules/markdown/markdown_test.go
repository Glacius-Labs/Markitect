func fixture() (core.SemanticModel, Config) {
	m := core.SemanticModel{Resources: []core.ModelResource{
		{Identity: core.ModelIdentity{APIVersion: core.APIVersion, Kind: "Rule", Name: "privacy", Key: "policy/Rule/privacy"}, Data: map[string]any{"text": "Keep data safe."}, Source: core.ModelSource{Path: "docs/policy/nested/privacy.yaml"}, Area: "policy"},
		{Identity: core.ModelIdentity{APIVersion: core.APIVersion, Kind: "Skill", Name: "review", Key: "policy/Skill/review"}, Data: map[string]any{"description": "Review changes.", "text": "See [the rule](../nested/privacy.yaml)."}, Source: core.ModelSource{Path: "docs/policy/skills/review.skill.yml"}, Area: "policy"},
	}}
	m.Relationships = []core.ModelRelationship{{From: "policy/Skill/review", To: "policy/Rule/privacy", Type: "uses"}, {From: "policy/Skill/review", To: "policy/Rule/privacy", Type: "unrelated"}}
	c := Config{Enabled: true, ProjectKey: "Project/sample", Areas: []Area{{Name: "policy", Path: "docs/policy"}}}
	return m, c
}

func TestGenerateMarkdownViewsAndNavigationFromSemanticModel(t *testing.T) {
	m, c := fixture()
	outputs, owners, err := Generate(m, c, nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range []string{"docs/markitect/policy/nested/privacy.rule.md", "docs/markitect/policy/skills/review.skill.md", "docs/markitect/policy/README.md", "docs/markitect/policy/nested/README.md", "docs/markitect/policy/skills/README.md", "docs/markitect/README.md"} {
		if outputs[p] == nil {
			t.Errorf("missing %s; got %v", p, sortedResourcePaths(outputs))
		}
	}
	body := string(outputs["docs/markitect/policy/skills/review.skill.md"])
	expected := "<!-- Generated by Markitect; source: docs/policy/skills/review.skill.yml -->\n# Skill: review\n\n**Description:** Review changes.\n\nSee [the rule](../nested/privacy.rule.md).\n\n## Dependencies\n\n- [Rule: privacy](../nested/privacy.rule.md)\n"
	if body != expected {
		t.Errorf("view bytes differ from the expected projection:\n--- got ---\n%s\n--- want ---\n%s", body, expected)
	}
	for _, want := range []string{"**Description:** Review changes.", "See [the rule](../nested/privacy.rule.md)."} {
		if !strings.Contains(body, want) {
			t.Errorf("view missing %q:\n%s", want, body)
		}
	}
	if !strings.Contains(body, "[Rule: privacy]") {
		t.Errorf("relationship projection missing:\n%s", body)
	}
	if strings.Contains(body, "unrelated") {
		t.Errorf("non-dependency relationship leaked into built-in view:\n%s", body)
	}
	if got := strings.Join(owners["docs/markitect/README.md"], ","); got != c.ProjectKey {
		t.Fatalf("root index owners %q", got)
	}
	second, _, err := Generate(m, c, nil)
	if err != nil {
		t.Fatal(err)
	}
	pathOwners, err := OutputPaths(m, c)
	if err != nil {
		t.Fatal(err)
	}
	if len(pathOwners) != len(outputs) {
		t.Fatalf("OutputPaths returned %d paths for %d generated outputs", len(pathOwners), len(outputs))
	}
	for p, b := range outputs {
		if string(b) != string(second[p]) {
			t.Fatalf("nondeterministic output %s", p)
		}
		if strings.Join(pathOwners[p], ",") != strings.Join(owners[p], ",") {
			t.Errorf("OutputPaths owners[%s]=%v, Generate owners=%v", p, pathOwners[p], owners[p])
		}
	}
}

func TestGenerateUsesFixedInputForCompanionAlias(t *testing.T) {
	m, c := fixture()
	m.Resources = m.Resources[:1]
	// The source-relative companion alias points at an ordinary file and must
	// retain that file when it exists without Markitect's ownership marker.
	m.Resources[0].Data["text"] = "See [companion](privacy.md)."
	files := map[string][]byte{"docs/policy/nested/privacy.md": []byte("Human-owned notes\n")}
	out, _, err := Generate(m, c, files)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out["docs/markitect/policy/nested/privacy.rule.md"]), "../../../policy/nested/privacy.md") {
		t.Fatalf("ordinary companion path was not retained: %s", out["docs/markitect/policy/nested/privacy.rule.md"])
	}
	files["docs/policy/nested/privacy.md"] = []byte("<!-- Generated by Markitect; source: old.yaml -->\n")
	out, _, err = Generate(m, c, files)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out["docs/markitect/policy/nested/privacy.rule.md"]), "(privacy.rule.md)") {
		t.Fatalf("generated companion alias was not redirected: %s", out["docs/markitect/policy/nested/privacy.rule.md"])
	}
}

