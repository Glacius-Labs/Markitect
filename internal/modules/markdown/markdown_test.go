func TestPackageDependencyUsesOnlyExplicitHostPinAndRetainsUnpinnedInstruction(t *testing.T) {
	consumer := core.ModelResource{Identity: core.ModelIdentity{APIVersion: core.APIVersion, Kind: "Skill", Name: "review", Key: "Skill/review"}, Data: map[string]any{"text": "Review."}, Source: core.ModelSource{Path: "docs/policy/review.yaml"}, Area: "policy"}
	dependency := core.ModelResource{Identity: core.ModelIdentity{APIVersion: core.APIVersion, Kind: "Rule", Namespace: "security", Name: "privacy", Package: "security-kit", Key: "security-kit::security/Rule/privacy"}, Data: map[string]any{}, Source: core.ModelSource{Path: ""}}
	m := core.SemanticModel{Resources: []core.ModelResource{consumer, dependency}, Relationships: []core.ModelRelationship{{From: consumer.Identity.Key, To: dependency.Identity.Key, Type: "uses"}}}
	c := Config{Enabled: true, ProjectKey: "Project/sample", Areas: []Area{{Name: "policy", Path: "docs/policy"}}, Packages: map[string]string{"security-kit": "2.4.1"}}
	out, _, err := Generate(m, c, nil)
	if err != nil {
		t.Fatal(err)
	}
	body := string(out["docs/markitect/policy/review.skill.md"])
	expected := "<!-- Generated by Markitect; source: docs/policy/review.yaml -->\n# Skill: review\n\nReview.\n\n## Dependencies\n\n- Package dependency: security-kit::security/Rule/privacy (version 2.4.1). Select this exported dependency with `markitect context --repo . --package security-kit --namespace security --kind Rule --name privacy`.\n"
	if body != expected {
		t.Fatalf("package dependency output differs from the legacy byte contract:\n--- got ---\n%s\n--- want ---\n%s", body, expected)
	}
	for _, want := range []string{"Package dependency: security-kit::security/Rule/privacy (version 2.4.1)", "markitect context --repo . --package security-kit --namespace security --kind Rule --name privacy"} {
		if !strings.Contains(body, want) {
			t.Errorf("package output missing %q:\n%s", want, body)
		}
	}
	c.Packages = nil
	out, _, err = Generate(m, c, nil)
	if err != nil {
		t.Fatal(err)
	}
	body = string(out["docs/markitect/policy/review.skill.md"])
	if strings.Contains(body, "(version ") || !strings.Contains(body, "markitect context --repo . --package security-kit") {
		t.Fatalf("missing pin should omit only the version: %s", body)
	}
}

