func TestProseNavigationSharesReferencesAcrossDescriptionAndText(t *testing.T) {
	g, files := proseGraph("[guide]: ../tools/README.md#help\n")
	g.Resources["general/Skill/setup"].Spec.Description = "Read [guide]."
	outputs, err := Generate(g, files)
	if err != nil {
		t.Fatal(err)
	}
	body := string(outputs["docs/markitect/general/skills/setup.skill.md"])
	if !strings.Contains(body, "**Description:** Read [guide].") || !strings.Contains(body, "[guide]: ../../../general/tools/README.md#help") {
		t.Fatalf("description reference was not projected from the complete prose: %s", body)
	}
}
