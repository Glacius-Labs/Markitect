type commonMarkExample struct {
	Markdown string `json:"markdown"`
	HTML     string `json:"html"`
	Example  int    `json:"example"`
	Section  string `json:"section"`
}

func decodeCommonMarkCorpus(t *testing.T) []byte {
	t.Helper()
	compressed, err := base64.StdEncoding.DecodeString(commonMarkCorpusGzipBase64)
	if err != nil {
		t.Fatalf("decode embedded CommonMark corpus: %v", err)
	}
	reader, err := gzip.NewReader(bytes.NewReader(compressed))
	if err != nil {
		t.Fatalf("open embedded CommonMark corpus: %v", err)
	}
	corpus, err := io.ReadAll(reader)
	closeErr := reader.Close()
	if err != nil {
		t.Fatalf("decompress embedded CommonMark corpus: %v", err)
	}
	if closeErr != nil {
		t.Fatalf("close embedded CommonMark corpus: %v", closeErr)
	}
	sum := sha256.Sum256(corpus)
	if got := hex.EncodeToString(sum[:]); got != commonMarkCorpusSHA256 {
		t.Fatalf("CommonMark 0.31.2 corpus SHA-256 = %s, want %s", got, commonMarkCorpusSHA256)
	}
	return corpus
}

// TestGoldmarkCommonMarkBaseline checks the pinned upstream CommonMark corpus
// against unextended Goldmark with raw HTML enabled, which is the spec's HTML
// rendering baseline. It does not exercise Markitect's body-link extension.
func TestGoldmarkCommonMarkBaseline(t *testing.T) {
	corpus := decodeCommonMarkCorpus(t)
	var examples []commonMarkExample
	if err := json.Unmarshal(corpus, &examples); err != nil {
		t.Fatalf("decode CommonMark corpus JSON: %v", err)
	}
	if len(examples) != 652 {
		t.Fatalf("CommonMark 0.31.2 corpus has %d examples, want 652", len(examples))
	}

	md := goldmark.New(goldmark.WithRendererOptions(
		html.WithXHTML(),
		html.WithUnsafe(),
	))
	var actual bytes.Buffer
	for _, example := range examples {
		actual.Reset()
		if err := md.Convert([]byte(example.Markdown), &actual); err != nil {
			t.Errorf("CommonMark example %d (%s): convert: %v", example.Example, example.Section, err)
			continue
		}
		if !bytes.Equal(actual.Bytes(), []byte(example.HTML)) {
			t.Errorf("CommonMark example %d (%s) differs from expected HTML\n got: %q\nwant: %q",
				example.Example, example.Section, actual.String(), example.HTML)
		}
	}
}
