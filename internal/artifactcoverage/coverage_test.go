func TestCheckFindsStaleDeclarationsAndOrphanGeneratedOutput(t *testing.T) {
	root := t.TempDir()
	write(t, root, "markitect.yaml", "apiVersion: markitect.example.org/v1alpha1\nkind: Project\nmetadata:\n  name: sample\nspec: {}\n")
	write(t, root, "managed/orphan.md", "<!-- Generated by Markitect; source: deleted.yaml -->\nold output\n")
	write(t, root, "managed/orphan.toml", "# Generated by Markitect; source: deleted.toml\nold output\n")
	write(t, root, "managed/schema/Project.yaml", "# Generated by Markitect; edit Go validation declarations.\n$schema: https://json-schema.org/draft/2020-12/schema\n")
	write(t, root, "managed/schema/Workflow.yaml", "# Generated by Markitect; edit Go validation declarations.\n$schema: https://json-schema.org/draft/2020-12/schema\n")
	write(t, root, "managed/schema/unknown.yaml", "# Generated by Markitect; unrelated generator output.\n")
	write(t, root, "managed/obsolete.txt", "old tool\n")
	write(t, root, "meta/coverage.yaml", `apiVersion: markitect.example.org/artifact-coverage/v1alpha1
kind: ArtifactCoverage
spec:
  roots: [managed, meta]
  tooling:
    - path: meta/coverage.yaml
      owner: artifact coverage policy
    - path: managed/schema/Project.yaml
      owner: project schema generator
    - path: managed/obsolete.txt
      owner: removed tool
  exclusions:
    - path: managed/deleted.txt
      reason: old exception
    - path: managed/schema/Workflow.yaml
      reason: schema produced by an external release task
`)
	report, err := Check(root, "meta/coverage.yaml")
	if err != nil {
		t.Fatal(err)
	}
	for _, expected := range [][2]string{{"orphan-generated", "managed/orphan.md"}, {"orphan-generated", "managed/orphan.toml"}, {"stale-exclusion", "managed/deleted.txt"}, {"unmanaged", "managed/schema/unknown.yaml"}} {
		if !hasFinding(report, expected[0], expected[1]) {
			t.Errorf("missing %s for %s: %#v", expected[0], expected[1], report.Findings)
		}
	}
	if !hasClass(report, "managed/schema/Project.yaml", "tooling") || !hasClass(report, "managed/schema/Workflow.yaml", "excluded") {
		t.Fatalf("non-renderer generated schema files were not accounted for: %#v", report.Files)
	}
	if err := os.Remove(filepath.Join(root, "managed/obsolete.txt")); err != nil {
		t.Fatal(err)
	}
	report, err = Check(root, "meta/coverage.yaml")
	if err != nil {
		t.Fatal(err)
	}
	if !hasFinding(report, "stale-tooling", "managed/obsolete.txt") {
		t.Fatalf("deleted tooling declaration was not reported: %#v", report.Findings)
	}
}

func hasFinding(report Report, code, name string) bool {
	for _, finding := range report.Findings {
		if finding.Code == code && finding.Path == name {
			return true
		}
	}
	return false
}

func hasClass(report Report, name, class string) bool {
	for _, file := range report.Files {
		if file.Path == name && file.Class == class {
			return true
		}
	}
	return false
}

func hasFindingMessage(report Report, code, text string) bool {
	for _, finding := range report.Findings {
		if finding.Code == code && strings.Contains(finding.Message, text) {
			return true
		}
	}
	return false
}

func write(t *testing.T, root, name, contents string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(contents), 0644); err != nil {
		t.Fatal(err)
	}
}
