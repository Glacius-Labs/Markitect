// Package documents implements the narrow generated-view target observation and
// guarded write port. It grants no artifact publication or run authority.
package documents

import (
	"bytes"
	"context"
	"crypto/sha256"
	"errors"
	"fmt"
	"io/fs"
	"os"

	"github.com/Glacius-Labs/Markitect/internal/modeldocs"
	"github.com/Glacius-Labs/Markitect/internal/tooling/guardedwrite"
)

type Writer struct{}

func (Writer) Observe(ctx context.Context, repository, path string) (target modeldocs.Target, err error) {
	target.Path = path
	if err := ctx.Err(); err != nil {
		return target, err
	}
	root, err := guardedwrite.OpenRoot(repository)
	if err != nil {
		return target, err
	}
	defer func() { err = errors.Join(err, root.Close()) }()
	before, err := root.Lstat(path)
	if errors.Is(err, fs.ErrNotExist) {
		return target, nil
	}
	if err != nil {
		return target, err
	}
	if !before.Mode().IsRegular() || before.Size() > 64<<20 {
		return target, errors.New("documentation target must be a regular file of at most 64 MiB")
	}
	data, err := root.ReadFile(path)
	if err != nil {
		return target, err
	}
	after, err := root.Lstat(path)
	if err != nil {
		return target, err
	}
	if !os.SameFile(before, after) || before.Size() != after.Size() || before.Mode() != after.Mode() || !before.ModTime().Equal(after.ModTime()) {
		return target, errors.New("documentation target changed during observation")
	}
	target.Exists = true
	target.Bytes = data
	target.Mode = uint32(after.Mode().Perm())
	target.ContentDigest = fmt.Sprintf("sha256:%x", sha256.Sum256(data))
	return target, ctx.Err()
}

func (w Writer) Write(ctx context.Context, repository string, expected modeldocs.Target, content []byte, validate, validateSources func() error) (modeldocs.WriteResult, error) {
	if err := ctx.Err(); err != nil {
		return modeldocs.WriteResult{}, err
	}
	capture, err := guardedwrite.CaptureFiles(repository, []string{expected.Path})
	if err != nil {
		return modeldocs.WriteResult{}, err
	}
	actual := capture.Files[expected.Path]
	if actual.Exists != expected.Exists || actual.Exists && (!bytes.Equal(actual.Bytes, expected.Bytes) || uint32(actual.Mode.Perm()) != expected.Mode) {
		return modeldocs.WriteResult{}, errors.New("documentation target differs from its reviewed preview")
	}
	mode := fs.FileMode(0644)
	if expected.Exists {
		mode = fs.FileMode(expected.Mode)
	}
	result, err := guardedwrite.ApplyOrderedChecked(repository, capture, []guardedwrite.Change{{Path: expected.Path, Bytes: content, Mode: mode}}, func() error {
		if err := ctx.Err(); err != nil {
			return err
		}
		return validate()
	}, func() error {
		if err := ctx.Err(); err != nil {
			return err
		}
		return validate()
	}, func(guardedwrite.Result) error {
		observed, err := w.Observe(ctx, repository, expected.Path)
		if err != nil {
			return err
		}
		if !observed.Exists || !bytes.Equal(observed.Bytes, content) {
			return errors.New("documentation target readback differs from generated bytes")
		}
		return validateSources()
	})
	return modeldocs.WriteResult{CompletedPaths: result.CompletedPaths}, err
}
