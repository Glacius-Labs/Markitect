// Package markdown projects the normalized semantic model into repository-local
// Markdown views. It never parses authoring YAML or writes files.
package markdown

import (
	"fmt"
	"net/url"
	"path"
	"sort"
	"strings"

	"github.com/Glacius-Labs/Markitect/internal/host/compat/v0_13/consumers/markdown/links"
	core "github.com/Glacius-Labs/Markitect/internal/host/compat/v0_13/kernel"
	"go.yaml.in/yaml/v3"
)

const (
	marker     = "Generated by Markitect"
	viewsRoot  = "docs/markitect"
	domainRoot = "docs/markitect/_domains"
)

// Area is a configured owner boundary for local semantic resources.
type Area struct{ Name, Path string }

// Config contains only the Markdown projection choices owned by the host.
type Config struct {
	Enabled    bool
	ProjectKey string
	Path       string
	Areas      []Area
	// Packages carries only explicit host-resolved pin versions used in output.
	// The Markdown module never reads or evaluates package authoring objects.
	Packages             map[string]string
	FunctionalPredicates []string
	DocumentationRoots   []string
}

// ViewPaths returns local typed-resource projection paths. Imported resources
// and the configured projection owner do not acquire local Markdown views.
func ViewPaths(model core.SemanticModel, config Config) (map[string]core.ModelResource, error) {
	paths := map[string]core.ModelResource{}
	if !config.Enabled {
		return paths, nil
	}
	resources := localResources(model)
	folded := map[string]string{}
	for _, r := range resources {
		if excluded(r, config) {
			continue
		}
		if r.Identity.Key == "" || r.Identity.Kind == "" || r.Identity.Name == "" {
			return nil, fmt.Errorf("Markdown resource identity requires key, kind, and name")
		}
		output, err := MarkdownViewPath(r, config)
		if err != nil {
			return nil, err
		}
		if prior, ok := folded[foldPath(output)]; ok {
			return nil, fmt.Errorf("Markdown view path collision: %q and %q", prior, output)
		}
		folded[foldPath(output)] = output
		paths[output] = r
	}
	return paths, nil
}

// DomainPaths returns contract views for custom domains with a matching fixed
// domain input. Built-in schemas have no project-owned source and are omitted.
func DomainPaths(model core.SemanticModel, config Config) (map[string]core.ModelDomain, error) {
	paths := map[string]core.ModelDomain{}
	if !config.Enabled {
		return paths, nil
	}
	inputs := map[string]core.ModelDomainInput{}
	inputOrder := append([]core.ModelDomainInput(nil), model.DomainInputs...)
	sort.Slice(inputOrder, func(i, j int) bool {
		if inputOrder[i].APIVersion != inputOrder[j].APIVersion {
			return inputOrder[i].APIVersion < inputOrder[j].APIVersion
		}
		return inputOrder[i].Path < inputOrder[j].Path
	})
	for _, input := range inputOrder {
		if previous, exists := inputs[input.APIVersion]; exists && (previous.Path != input.Path || previous.Package != input.Package) {
			return nil, fmt.Errorf("domain input collision for API version %q: %q and %q", input.APIVersion, previous.Path, input.Path)
		}
		inputs[input.APIVersion] = input
	}
	folded := map[string]string{}
	domains := append([]core.ModelDomain(nil), model.Domains...)
	sort.Slice(domains, func(i, j int) bool { return domains[i].APIVersion < domains[j].APIVersion })
	for _, domain := range domains {
		input, ok := inputs[domain.APIVersion]
		if domain.Name == "" || domain.APIVersion == "" || domain.APIVersion == core.APIVersion || !ok || input.Path == "" {
			continue
		}
		if err := validPath(input.Path); err != nil {
			return nil, fmt.Errorf("domain input %s source path: %w", domain.APIVersion, err)
		}
		output, err := DomainMarkdownPath(domain, input.Path)
		if err != nil {
			return nil, err
		}
		if prior, ok := folded[foldPath(output)]; ok {
			return nil, fmt.Errorf("domain contract view path collision: %q and %q", prior, output)
		}
		folded[foldPath(output)] = output
		paths[output] = domain
	}
	return paths, nil
}

// DomainPathsWithSources preserves each exact source path for render provenance.
func DomainPathsWithSources(model core.SemanticModel, config Config) (map[string]core.ModelDomainInput, map[string]core.ModelDomain, error) {
	domains, err := DomainPaths(model, config)
	if err != nil {
		return nil, nil, err
	}
	sources := map[string]core.ModelDomainInput{}
	byVersion := map[string]core.ModelDomainInput{}
	for _, input := range model.DomainInputs {
		byVersion[input.APIVersion] = input
	}
	for output, domain := range domains {
		sources[output] = byVersion[domain.APIVersion]
	}
	return sources, domains, nil
}

func MarkdownViewPath(r core.ModelResource, config Config) (string, error) {
	i := r.Identity
	if excluded(r, config) {
		return "", fmt.Errorf("resource %s has no local Markdown view", i.Key)
	}
	var area *Area
	for n := range config.Areas {
		a := &config.Areas[n]
		if a.Name == r.Area {
			if area != nil {
				return "", fmt.Errorf("resource %s has ambiguous owning Area %q", i.Key, r.Area)
			}
			area = a
		}
	}
	if area == nil {
		return "", fmt.Errorf("resource %s has no owning Area", i.Key)
	}
	if area.Name == "" || area.Name == "." || area.Name == ".." || strings.ContainsAny(area.Name, `/\\:`) || strings.ContainsRune(area.Name, 0) {
		return "", fmt.Errorf("Area name %q is not a safe path segment", area.Name)
	}
	root := strings.TrimSuffix(area.Path, "/")
	source := r.Source.Path
	if root == "" || (source != root && !strings.HasPrefix(source, root+"/")) {
		return "", fmt.Errorf("resource %q is outside its owning Area %q", source, area.Path)
	}
	relative := strings.TrimPrefix(strings.TrimPrefix(source, root), "/")
	if relative == "" || path.IsAbs(relative) || path.Clean(relative) != relative || strings.HasPrefix(relative, "../") || strings.ContainsAny(relative, "\\:\x00") {
		return "", fmt.Errorf("resource path %q is not normalized within Area %q", source, area.Path)
	}
	stem := strings.TrimSuffix(relative, path.Ext(relative))
	suffix := "." + strings.ToLower(i.Kind)
	if i.APIVersion != "" && i.APIVersion != core.APIVersion {
		parts := strings.Split(i.APIVersion, "/")
		if len(parts) == 2 {
			suffix += "." + strings.ReplaceAll(parts[0], "/", ".") + "." + parts[1]
		}
	}
	if !strings.HasSuffix(strings.ToLower(stem), suffix) {
		stem += suffix
	}
	output := path.Join(viewsRoot, area.Name, path.Dir(stem), path.Base(stem)+".md")
	if err := validPath(output); err != nil {
		return "", fmt.Errorf("Markdown view output: %w", err)
	}
	return output, nil
}

// DomainMarkdownPath constructs a safe view path from a normalized domain identity.
func DomainMarkdownPath(domain core.ModelDomain, source string) (string, error) {
	parts := strings.Split(domain.APIVersion, "/")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" || domain.Name == "" || source == "" {
		return "", fmt.Errorf("domain contract requires name, source path, and group/version apiVersion")
	}
	if err := validPath(source); err != nil {
		return "", fmt.Errorf("domain contract source path: %w", err)
	}
	out := path.Join(domainRoot, safePart(parts[0])+"."+safePart(parts[1])+".domain.md")
	if err := validPath(out); err != nil {
		return "", fmt.Errorf("domain contract output path: %w", err)
	}
	return out, nil
}
func safePart(v string) string {
	var b strings.Builder
	for i := 0; i < len(v); i++ {
		c := v[i]
		if c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '.' || c == '-' {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "_%02x", c)
		}
	}
	return b.String()
}

// Generate returns deterministic Markdown files and the exact semantic owners
// of those files. files is the fixed source snapshot used for prose aliases.
func Generate(model core.SemanticModel, config Config, files map[string][]byte) (map[string][]byte, map[string][]string, error) {
	outputs := map[string][]byte{}
	ownerSets := map[string]map[string]bool{}
	if !config.Enabled {
		return outputs, map[string][]string{}, nil
	}
	plan, err := buildPlan(model, config)
	if err != nil {
		return nil, nil, err
	}
	views, domains, domainSources := plan.views, plan.domains, plan.domainSources
	nav, err := newNavigation(model, config, files)
	if err != nil {
		return nil, nil, err
	}
	keys := sortedResourcePaths(views)
	for _, output := range keys {
		r := views[output]
		body, err := renderResource(r, output, model, config, nav)
		if err != nil {
			return nil, nil, err
		}
		if err = addOwned(outputs, ownerSets, output, body, r.Identity.Key); err != nil {
			return nil, nil, err
		}
	}
	for _, output := range sortedResourcePaths(domains) {
		d := domains[output]
		source := domainSources[output]
		body, err := renderDomain(d, source, output, model, nav)
		if err != nil {
			return nil, nil, err
		}
		owner := "domain:" + d.APIVersion + "/" + d.Name
		if err = addOwned(outputs, ownerSets, output, body, owner); err != nil {
			return nil, nil, err
		}
	}
	if len(views) > 0 || len(domains) > 0 {
		if config.ProjectKey == "" {
			return nil, nil, fmt.Errorf("Markdown projection requires a Project owner key")
		}
		if config.Path != "" {
			if err := validPath(config.Path); err != nil {
				return nil, nil, fmt.Errorf("Project source path: %w", err)
			}
		}
		if err := addNavigation(outputs, ownerSets, views, domains, domainSources, config.ProjectKey, config.Path); err != nil {
			return nil, nil, err
		}
	}
	if err := checkCollisions(outputs, model); err != nil {
		return nil, nil, err
	}
	owners := map[string][]string{}
	for p, set := range ownerSets {
		for k := range set {
			owners[p] = append(owners[p], k)
		}
		sort.Strings(owners[p])
	}
	return outputs, owners, nil
}

type projectionPlan struct {
	views         map[string]core.ModelResource
	domains       map[string]core.ModelDomain
	domainSources map[string]core.ModelDomainInput
	owners        map[string][]string
}

// OutputPaths returns all generated paths and owners without rendering bytes
// or inspecting prose. Host uses this to reserve outputs before input analysis.
func OutputPaths(model core.SemanticModel, config Config) (map[string][]string, error) {
	plan, err := buildPlan(model, config)
	if err != nil {
		return nil, err
	}
	return plan.owners, nil
}

func buildPlan(model core.SemanticModel, config Config) (projectionPlan, error) {
	plan := projectionPlan{views: map[string]core.ModelResource{}, domains: map[string]core.ModelDomain{}, domainSources: map[string]core.ModelDomainInput{}, owners: map[string][]string{}}
	if !config.Enabled {
		return plan, nil
	}
	if err := checkCollisions(map[string][]byte{}, model); err != nil {
		return projectionPlan{}, err
	}
	var err error
	plan.views, err = ViewPaths(model, config)
	if err != nil {
		return projectionPlan{}, err
	}
	plan.domainSources, plan.domains, err = DomainPathsWithSources(model, config)
	if err != nil {
		return projectionPlan{}, err
	}
	if len(plan.views) > 0 || len(plan.domains) > 0 {
		if config.ProjectKey == "" {
			return projectionPlan{}, fmt.Errorf("Markdown projection requires a Project owner key")
		}
		if config.Path != "" {
			if err := validPath(config.Path); err != nil {
				return projectionPlan{}, fmt.Errorf("Project source path: %w", err)
			}
		}
	}
	paths := map[string][]string{}
	for output, r := range plan.views {
		paths[output] = []string{r.Identity.Key}
	}
	for output, d := range plan.domains {
		paths[output] = []string{"domain:" + d.APIVersion + "/" + d.Name}
	}
	if len(plan.views) > 0 || len(plan.domains) > 0 {
		for _, dir := range navigationDirectories(plan.views, plan.domains) {
			output := path.Join(dir, "README.md")
			if _, exists := paths[output]; exists {
				return projectionPlan{}, fmt.Errorf("duplicate generated output %q", output)
			}
			paths[output] = []string{config.ProjectKey}
		}
	}
	fake := make(map[string][]byte, len(paths))
	for output := range paths {
		if err := validPath(output); err != nil {
			return projectionPlan{}, fmt.Errorf("invalid output path %q: %w", output, err)
		}
		fake[output] = nil
	}
	if err := checkCollisions(fake, model); err != nil {
		return projectionPlan{}, err
	}
	folded := map[string]string{}
	for _, output := range sortedResourcePaths(paths) {
		key := foldPath(output)
		if previous, ok := folded[key]; ok {
			return projectionPlan{}, fmt.Errorf("output path collision: %q and %q", previous, output)
		}
		folded[key] = output
	}
	plan.owners = paths
	for _, owners := range plan.owners {
		sort.Strings(owners)
	}
	return plan, nil
}

func localResources(m core.SemanticModel) []core.ModelResource {
	out := make([]core.ModelResource, 0, len(m.Resources))
	for _, r := range m.Resources {
		if r.Identity.Package == "" {
			out = append(out, r)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Source.Path != out[j].Source.Path {
			return out[i].Source.Path < out[j].Source.Path
		}
		return out[i].Identity.Key < out[j].Identity.Key
	})
	return out
}
func excluded(r core.ModelResource, config Config) bool {
	return r.Identity.Package != "" || r.Identity.Key == config.ProjectKey
}
func sortedResourcePaths[T any](m map[string]T) []string {
	out := make([]string, 0, len(m))
	for p := range m {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}
func foldPath(p string) string { return strings.ToLower(p) }
func validPath(p string) error {
	if p == "" || strings.ContainsAny(p, "\\:\x00") || strings.HasPrefix(p, "/") || path.Clean(p) != p || p == "." || strings.HasPrefix(p, "../") {
		return fmt.Errorf("path must be repository-relative and normalized")
	}
	for _, part := range strings.Split(p, "/") {
		if part == "" || part == "." || part == ".." {
			return fmt.Errorf("path contains unsafe component")
		}
	}
	return nil
}
func addOwned(outputs map[string][]byte, owners map[string]map[string]bool, p string, b []byte, owner string) error {
	if err := validPath(p); err != nil {
		return fmt.Errorf("invalid output path %q: %w", p, err)
	}
	if _, ok := outputs[p]; ok {
		return fmt.Errorf("duplicate generated output %q", p)
	}
	outputs[p] = b
	if owners[p] == nil {
		owners[p] = map[string]bool{}
	}
	owners[p][owner] = true
	return nil
}
func checkCollisions(outputs map[string][]byte, m core.SemanticModel) error {
	seen := map[string]string{}
	identitySources := map[string]string{}
	for _, r := range localResources(m) {
		if r.Source.Path == "" {
			return fmt.Errorf("resource %s has an empty source path", r.Identity.Key)
		}
		if err := validPath(r.Source.Path); err != nil {
			return fmt.Errorf("resource %s source path: %w", r.Identity.Key, err)
		}
		k := foldPath(r.Source.Path)
		if p, ok := seen[k]; ok {
			return fmt.Errorf("source path collision: %q and %q", p, r.Source.Path)
		}
		if previous, ok := identitySources[r.Identity.Key]; ok && previous != r.Source.Path {
			return fmt.Errorf("resource identity collision: %q has sources %q and %q", r.Identity.Key, previous, r.Source.Path)
		}
		identitySources[r.Identity.Key] = r.Source.Path
		seen[k] = r.Source.Path
	}
	for _, p := range sortedResourcePaths(outputs) {
		k := foldPath(p)
		if prior, ok := seen[k]; ok {
			return fmt.Errorf("output path collision: source %q conflicts with %q", prior, p)
		}
		seen[k] = p
	}
	return nil
}

type navigation struct {
	files      map[string][]byte
	companions map[string][]core.ModelResource
	sources    map[string]core.ModelResource
	paths      map[string]string
	config     Config
}

func newNavigation(m core.SemanticModel, c Config, files map[string][]byte) (*navigation, error) {
	n := &navigation{files: files, companions: map[string][]core.ModelResource{}, sources: map[string]core.ModelResource{}, paths: map[string]string{}, config: c}
	for _, r := range localResources(m) {
		if excluded(r, c) {
			continue
		}
		if old, ok := n.sources[r.Source.Path]; ok && old.Identity.Key != r.Identity.Key {
			return nil, fmt.Errorf("duplicate source path %q", r.Source.Path)
		}
		n.sources[r.Source.Path] = r
		n.companions[companionPath(r.Source.Path)] = append(n.companions[companionPath(r.Source.Path)], r)
		p, err := MarkdownViewPath(r, c)
		if err != nil {
			return nil, err
		}
		n.paths[r.Identity.Key] = p
	}
	return n, nil
}
func (n *navigation) rewrite(text string, r core.ModelResource, output string) (string, error) {
	out, err := links.Rewrite(text, func(dest string) (string, error) {
		if len(dest) >= 3 && isAlpha(dest[0]) && dest[1] == ':' && (dest[2] == '/' || dest[2] == '\\') {
			return "", fmt.Errorf("Markdown destination %q is not a portable relative path", dest)
		}
		if strings.HasPrefix(dest, "/") || strings.HasPrefix(dest, "#") || strings.HasPrefix(dest, "?") || hasScheme(dest) {
			return dest, nil
		}
		u, e := url.Parse(dest)
		if e != nil {
			return "", fmt.Errorf("invalid Markdown destination %q: %w", dest, e)
		}
		if u.IsAbs() || u.Host != "" || strings.HasPrefix(u.Path, "/") || u.Path == "" {
			return dest, nil
		}
		if strings.ContainsAny(u.Path, "\\:\x00") {
			return "", fmt.Errorf("Markdown destination %q is not a portable relative path", dest)
		}
		src := path.Clean(path.Join(path.Dir(r.Source.Path), u.Path))
		if src == ".." || strings.HasPrefix(src, "../") {
			return "", fmt.Errorf("Markdown destination %q escapes the repository", dest)
		}
		target := src
		if typed, ok := n.sources[src]; ok {
			target = n.paths[typed.Identity.Key]
		}
		if aliases := n.companions[src]; len(aliases) > 0 {
			data, exists := n.files[src]
			if !exists || isGenerated(data) {
				if len(aliases) != 1 {
					return "", fmt.Errorf("Markdown destination %q is an ambiguous companion alias", dest)
				}
				target = aliases[0].Source.Path
				if p, ok := n.paths[aliases[0].Identity.Key]; ok {
					target = p
				}
			}
		}
		encoded := relative(output, target)
		if strings.HasSuffix(u.Path, "/") && !strings.HasSuffix(encoded, "/") {
			encoded += "/"
		}
		u.Path, e = url.PathUnescape(encoded)
		if e != nil {
			return "", e
		}
		u.RawPath = encoded
		return u.String(), nil
	})
	if err != nil {
		return "", fmt.Errorf("resource %s prose navigation: %w", r.Identity.Key, err)
	}
	return out, nil
}
func hasScheme(s string) bool {
	end := strings.IndexByte(s, ':')
	if end <= 0 {
		return false
	}
	for i := 0; i < end; i++ {
		c := s[i]
		if isAlpha(c) {
			continue
		}
		if i > 0 && (c >= '0' && c <= '9' || c == '+' || c == '-' || c == '.') {
			continue
		}
		return false
	}
	return true
}
func isAlpha(c byte) bool { return c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' }
func companionPath(source string) string {
	ext := path.Ext(source)
	if ext == "" {
		return source + ".md"
	}
	return strings.TrimSuffix(source, ext) + ".md"
}
func relative(fromFile, toFile string) string {
	from := strings.Split(strings.Trim(path.Dir(fromFile), "/"), "/")
	to := strings.Split(strings.Trim(toFile, "/"), "/")
	if len(from) == 1 && from[0] == "" {
		from = nil
	}
	i := 0
	for i < len(from) && i < len(to) && from[i] == to[i] {
		i++
	}
	parts := make([]string, 0, len(from)-i+len(to)-i)
	for range from[i:] {
		parts = append(parts, "..")
	}
	parts = append(parts, to[i:]...)
	if len(parts) == 0 {
		return "."
	}
	for i, p := range parts {
		parts[i] = url.PathEscape(p)
	}
	return strings.Join(parts, "/")
}
func isGenerated(data []byte) bool {
	text := strings.TrimSpace(string(data))
	if strings.HasPrefix(text, "---\n") || strings.HasPrefix(text, "---\r\n") {
		lines := strings.Split(text, "\n")
		closed := false
		for i := 1; i < len(lines); i++ {
			if strings.TrimSpace(lines[i]) == "---" {
				text = strings.TrimSpace(strings.Join(lines[i+1:], "\n"))
				closed = true
				break
			}
		}
		if !closed {
			return false
		}
	}
	return strings.HasPrefix(text, "<!-- Generated by Markitect;") || strings.HasPrefix(text, "# Generated by Markitect;") || strings.HasPrefix(text, "<!-- Generated by Markitect -->")
}

func renderResource(r core.ModelResource, output string, m core.SemanticModel, c Config, n *navigation) ([]byte, error) {
	if r.Identity.APIVersion != "" && r.Identity.APIVersion != core.APIVersion {
		return renderGeneric(r, output, m, c, n)
	}
	var b strings.Builder
	b.WriteString("<!-- " + marker + "; source: " + r.Source.Path + " -->\n# " + r.Identity.Kind + ": " + r.Identity.Name + "\n\n")
	var prose strings.Builder
	if d, ok := r.Data["description"].(string); ok && d != "" {
		prose.WriteString("**Description:** " + d + "\n\n")
	}
	if text, ok := r.Data["text"].(string); ok && text != "" {
		prose.WriteString(text)
		if !strings.HasSuffix(text, "\n") {
			prose.WriteByte('\n')
		}
	}
	rewritten, err := n.rewrite(prose.String(), r, output)
	if err != nil {
		return nil, err
	}
	b.WriteString(rewritten)
	rels := relationLinks(r, output, m, n)
	if len(rels) > 0 {
		b.WriteString("\n## Dependencies\n\n")
		for _, line := range rels {
			b.WriteString(line + "\n")
		}
	}
	return []byte(b.String()), nil
}
func renderGeneric(r core.ModelResource, output string, m core.SemanticModel, c Config, n *navigation) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s; source: %s -->\n# %s: %s\n\n**API version:** `%s`\n\n", marker, r.Source.Path, r.Identity.Kind, r.Identity.Name, r.Identity.APIVersion)
	if d, ok := r.Data["description"].(string); ok && strings.TrimSpace(d) != "" {
		b.WriteString(d + "\n\n")
	}
	fields := make([]string, 0, len(r.Data))
	for k := range r.Data {
		if k != "description" {
			fields = append(fields, k)
		}
	}
	sort.Strings(fields)
	if len(fields) > 0 {
		b.WriteString("## Declared facts\n\n")
		for _, k := range fields {
			fmt.Fprintf(&b, "- **%s:** %s\n", markdownText(k), displayValue(r.Data[k]))
		}
		b.WriteByte('\n')
	}
	rels := relationLinks(r, output, m, n)
	if len(rels) > 0 {
		b.WriteString("## Relationships\n\n")
		for _, line := range rels {
			b.WriteString(line + "\n")
		}
		b.WriteByte('\n')
	}
	con := constraints(r, m)
	if len(con) > 0 {
		b.WriteString("## Applicable constraints\n\n")
		for _, item := range con {
			fmt.Fprintf(&b, "- **%s:** %s\n", item.Name, item.Text)
		}
		b.WriteByte('\n')
	}
	writePolicy(&b, r.Identity.APIVersion, r.Identity.Key, m, output, n)
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

type namedText struct{ Name, Text string }

func constraints(r core.ModelResource, m core.SemanticModel) []namedText {
	var out []namedText
	for _, d := range m.Domains {
		if d.APIVersion != r.Identity.APIVersion {
			continue
		}
		for _, x := range d.Constraints {
			if x.Select.Kind != "" && x.Select.Kind != r.Identity.Kind {
				continue
			}
			if x.Assert.Relation != "" && (x.Assert.Op == "count" || x.Assert.Op == "allowed-targets") {
				if relation, ok := d.Relations[x.Assert.Relation]; ok && len(relation.SourceKinds) > 0 && !containsKind(relation.SourceKinds, r.Identity.Kind) {
					continue
				}
			}
			match := true
			for k, v := range x.Select.Labels {
				if r.Labels[k] != v {
					match = false
					break
				}
			}
			if !match {
				continue
			}
			text := assertionText(x.Assert, d)
			if x.Description != "" {
				text += " Explanation: " + x.Description
			}
			out = append(out, namedText{x.Name, text})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func containsKind(kinds []string, kind string) bool {
	for _, candidate := range kinds {
		if candidate == kind {
			return true
		}
	}
	return false
}
func assertionText(a core.ConstraintAssertion, d core.ModelDomain) string {
	switch a.Op {
	case "present":
		return fmt.Sprintf("`%s` must be present.", a.Field)
	case "equal":
		return fmt.Sprintf("`%s` must equal %s.", a.Field, displayValue(a.Value))
	case "allowed":
		return fmt.Sprintf("`%s` must be one of %s.", a.Field, displayValue(a.Values))
	case "allowed-targets":
		return fmt.Sprintf("`%s` relationships may target only kinds %s.", relationField(d, a.Relation), displayValue(a.Values))
	case "same-target":
		return fmt.Sprintf("Paths `%s` and `%s` must each resolve exactly one target per step and end at the same canonical identity.", strings.Join(a.Left, " → "), strings.Join(a.Right, " → "))
	case "unique":
		return fmt.Sprintf("`%s` must be unique across the selected resources.", a.Field)
	case "count":
		what := "selected resources"
		if a.Relation != "" {
			what = "`" + relationField(d, a.Relation) + "` relationship targets"
		}
		bounds := ""
		if a.Min != nil && a.Max != nil {
			bounds = fmt.Sprintf("between %d and %d", *a.Min, *a.Max)
		} else if a.Min != nil {
			bounds = fmt.Sprintf("at least %d", *a.Min)
		} else if a.Max != nil {
			bounds = fmt.Sprintf("at most %d", *a.Max)
		}
		if a.Scope == "resource" {
			return fmt.Sprintf("Each selected resource's count of %s must be %s.", what, bounds)
		}
		return fmt.Sprintf("The selection-wide count of %s must be %s.", what, bounds)
	default:
		return "The declared structured assertion must hold."
	}
}
func relationField(d core.ModelDomain, rel string) string {
	if x, ok := d.Relations[rel]; ok && x.Field != "" {
		return x.Field
	}
	return rel
}
func relationLinks(r core.ModelResource, output string, m core.SemanticModel, n *navigation) []string {
	byKey := map[string]core.ModelResource{}
	for _, x := range m.Resources {
		byKey[x.Identity.Key] = x
	}
	type dependency struct{ label, line string }
	var builtIn []dependency
	var generic []string
	seen := map[string]bool{}
	builtInRefs := r.Identity.APIVersion == "" || r.Identity.APIVersion == core.APIVersion
	for _, rel := range m.Relationships {
		if rel.From != r.Identity.Key {
			continue
		}
		if (r.Identity.APIVersion == "" || r.Identity.APIVersion == core.APIVersion) && rel.Type != "rules" && rel.Type != "uses" && rel.Type != "needs" && rel.Type != "implements" {
			continue
		}
		d, ok := byKey[rel.To]
		if !ok {
			continue
		}
		if builtInRefs {
			if seen[d.Identity.Key] {
				continue
			}
			seen[d.Identity.Key] = true
		}
		label := rel.Type + " " + d.Identity.Kind + ": " + d.Identity.Name
		if r.Identity.APIVersion == "" || r.Identity.APIVersion == core.APIVersion {
			label = d.Identity.Kind + ": " + d.Identity.Name
		}
		if d.Identity.Package != "" {
			if r.Identity.APIVersion == "" || r.Identity.APIVersion == core.APIVersion {
				label := "Package dependency: " + d.Identity.Key
				if version := n.config.Packages[d.Identity.Package]; version != "" {
					label += " (version " + version + ")"
				}
				instruction := "Select this exported dependency with `markitect context --repo . --package " + d.Identity.Package + " --namespace " + d.Identity.Namespace + " --kind " + d.Identity.Kind + " --name " + d.Identity.Name + "`."
				builtIn = append(builtIn, dependency{label: label, line: "- " + label + ". " + instruction})
				continue
			}
			generic = append(generic, "- `"+rel.Type+"` → "+label+" (package `"+d.Identity.Package+"`)")
			continue
		}
		target := d.Source.Path
		if view, ok := n.paths[d.Identity.Key]; ok {
			target = view
		}
		if r.Identity.APIVersion == "" || r.Identity.APIVersion == core.APIVersion {
			builtIn = append(builtIn, dependency{label: label, line: "- [" + label + "](" + relative(output, target) + ")"})
		} else {
			generic = append(generic, "- [`"+rel.Type+"` → "+label+"]("+relative(output, target)+")")
		}
	}
	if builtInRefs {
		sort.Slice(builtIn, func(i, j int) bool {
			if builtIn[i].label != builtIn[j].label {
				return builtIn[i].label < builtIn[j].label
			}
			return builtIn[i].line < builtIn[j].line
		})
		out := make([]string, 0, len(builtIn))
		for _, item := range builtIn {
			out = append(out, item.line)
		}
		return out
	}
	sort.Strings(generic)
	return unique(generic)
}
func unique(v []string) []string {
	if len(v) < 2 {
		return v
	}
	out := v[:1]
	for _, x := range v[1:] {
		if x != out[len(out)-1] {
			out = append(out, x)
		}
	}
	return out
}

func renderDomain(d core.ModelDomain, input core.ModelDomainInput, target string, m core.SemanticModel, n *navigation) ([]byte, error) {
	type schema struct {
		APIVersion  string                             `yaml:"apiVersion"`
		Kinds       map[string]core.KindDefinition     `yaml:"kinds"`
		Relations   map[string]core.RelationDefinition `yaml:"relations,omitempty"`
		Constraints []core.ConstraintDefinition        `yaml:"constraints,omitempty"`
	}
	encoded, err := yaml.Marshal(schema{d.APIVersion, d.Kinds, d.Relations, d.Constraints})
	if err != nil {
		return nil, fmt.Errorf("encode normalized domain %s: %w", d.APIVersion, err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s; source: %s -->\n# Domain contract: %s\n\n- **API version:** `%s`\n- **Definition source:** `%s`\n\n## Normalized schema and policy\n\n```yaml\n", marker, input.Path, markdownText(d.Name), markdownCode(d.APIVersion), markdownCode(input.Path))
	b.Write(encoded)
	b.WriteString("```\n\n")
	writePolicy(&b, d.APIVersion, "", m, target, n)
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func writePolicy(b *strings.Builder, apiVersion, subject string, m core.SemanticModel, target string, n *navigation) {
	var results []core.PolicyResult
	for _, x := range m.PolicyResults {
		if x.APIVersion == apiVersion && (subject == "" || x.Subject == subject) {
			results = append(results, x)
		}
	}
	if subject != "" && len(results) == 0 {
		return
	}
	sort.Slice(results, func(i, j int) bool {
		if results[i].Constraint != results[j].Constraint {
			return results[i].Constraint < results[j].Constraint
		}
		return results[i].Subject < results[j].Subject
	})
	b.WriteString("## Policy outcomes\n\n")
	if len(results) == 0 {
		b.WriteString("No policy outcomes were evaluated for this domain.\n\n")
		return
	}
	b.WriteString("| Constraint | Subject | Status | Result | Waiver details |\n| --- | --- | --- | --- | --- |\n")
	byKey := map[string]core.ModelResource{}
	for _, r := range m.Resources {
		byKey[r.Identity.Key] = r
	}
	for _, x := range results {
		subjectLabel := "All selected subjects"
		if x.Subject != "" {
			subjectLabel = policySubject(x.Subject, byKey, target, n)
		}
		message := x.Message
		if message == "" {
			message = statusMessage(x.Status)
		}
		waiver := "—"
		if x.Status == core.PolicyWaived {
			parts := []string{"exception: " + x.ExceptionName, "rationale: " + x.Rationale, "owner: " + x.Owner, "decision: " + x.Decision}
			if x.ExpiresOn != "" {
				parts = append(parts, "expiresOn: "+x.ExpiresOn)
			}
			if x.PolicyDate != "" {
				parts = append(parts, "policyDate: "+x.PolicyDate)
			}
			waiver = markdownCell(strings.Join(parts, "; "))
		}
		fmt.Fprintf(b, "| `%s` | %s | **%s** | %s | %s |\n", markdownCell(x.Constraint), subjectLabel, markdownText(strings.ToUpper(x.Status)), markdownCell(message), waiver)
	}
	b.WriteByte('\n')
}
func policySubject(key string, resources map[string]core.ModelResource, target string, n *navigation) string {
	r, ok := resources[key]
	if !ok {
		return markdownCode(key)
	}
	label := r.Identity.Kind + ": " + r.Identity.Name
	if r.Identity.Namespace != "" {
		label = r.Identity.Namespace + "/" + label
	}
	if r.Identity.Package != "" {
		return markdownCode(label + " (package " + r.Identity.Package + ")")
	}
	if n != nil {
		if view, ok := n.paths[key]; ok {
			return "[" + markdownText(label) + "](" + relative(target, view) + ")"
		}
	}
	return markdownCode(label)
}
func statusMessage(status string) string {
	switch status {
	case core.PolicyPassed:
		return "Constraint passed."
	case core.PolicyFailed:
		return "Constraint failed."
	case core.PolicyWaived:
		return "Violation waived."
	default:
		return "Policy evaluation status: " + status
	}
}
func displayValue(v any) string {
	switch x := v.(type) {
	case nil:
		return "`null`"
	case string:
		return "`" + strings.ReplaceAll(x, "`", "\\`") + "`"
	case bool, int, int64, float64:
		return fmt.Sprintf("`%v`", x)
	case []any:
		if len(x) == 0 {
			return "`[]`"
		}
		a := make([]string, 0, len(x))
		for _, item := range x {
			a = append(a, displayValue(item))
		}
		return strings.Join(a, ", ")
	case map[string]any:
		if len(x) == 0 {
			return "`{}`"
		}
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		a := make([]string, 0, len(keys))
		for _, k := range keys {
			a = append(a, "`"+k+"`: "+displayValue(x[k]))
		}
		return strings.Join(a, "; ")
	default:
		return "`" + fmt.Sprint(x) + "`"
	}
}
func markdownCode(s string) string { return strings.ReplaceAll(s, "`", "\\`") }
func markdownText(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	for _, c := range []string{"`", "*", "_", "[", "]", "<", ">", "|"} {
		s = strings.ReplaceAll(s, c, "\\"+c)
	}
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r", " "), "\n", " ")
}
func markdownCell(s string) string { return markdownText(s) }

func addNavigation(outputs map[string][]byte, owners map[string]map[string]bool, views map[string]core.ModelResource, domains map[string]core.ModelDomain, sources map[string]core.ModelDomainInput, projectKey, projectPath string) error {
	if projectPath == "" {
		projectPath = "markitect.yaml"
	}
	direct := map[string][]string{}
	children := map[string]map[string]bool{}
	dirsSorted := navigationDirectories(views, domains)
	for view := range views {
		dir := path.Dir(view)
		direct[dir] = append(direct[dir], path.Base(view))
		for dir != viewsRoot && strings.HasPrefix(dir, viewsRoot+"/") {
			parent := path.Dir(dir)
			if children[parent] == nil {
				children[parent] = map[string]bool{}
			}
			children[parent][path.Base(dir)] = true
			dir = parent
		}
	}
	if len(domains) > 0 {
		if children[viewsRoot] == nil {
			children[viewsRoot] = map[string]bool{}
		}
		children[viewsRoot][path.Base(domainRoot)] = true
		for view := range domains {
			direct[domainRoot] = append(direct[domainRoot], path.Base(view))
		}
	}
	for _, dir := range dirsSorted {
		file := path.Join(dir, "README.md")
		if dir == domainRoot {
			body := domainIndex(domains, sources, file, projectPath)
			if err := addOwned(outputs, owners, file, body, projectKey); err != nil {
				return err
			}
			continue
		}
		var b strings.Builder
		fmt.Fprintf(&b, "<!-- %s; source: %s -->\n# Markitect views\n\n", marker, projectPath)
		names := direct[dir]
		sort.Strings(names)
		for _, name := range names {
			view := path.Join(dir, name)
			if d, ok := domains[view]; ok {
				label := "Domain contract: " + d.Name + " (" + d.APIVersion + ")"
				fmt.Fprintf(&b, "- [%s](%s)\n", markdownText(label), relative(file, view))
				continue
			}
			r := views[view]
			fmt.Fprintf(&b, "- [%s: %s](%s)\n", r.Identity.Kind, r.Identity.Name, relative(file, view))
		}
		kids := make([]string, 0, len(children[dir]))
		for k := range children[dir] {
			kids = append(kids, k)
		}
		sort.Strings(kids)
		for _, kid := range kids {
			to := path.Join(dir, kid, "README.md")
			fmt.Fprintf(&b, "- [%s](%s)\n", kid, relative(file, to))
		}
		if err := addOwned(outputs, owners, file, []byte(b.String()), projectKey); err != nil {
			return err
		}
	}
	return nil
}

func navigationDirectories(views map[string]core.ModelResource, domains map[string]core.ModelDomain) []string {
	dirs := map[string]bool{viewsRoot: true}
	for view := range views {
		dir := path.Dir(view)
		for dir != viewsRoot && strings.HasPrefix(dir, viewsRoot+"/") {
			dirs[dir] = true
			dir = path.Dir(dir)
		}
	}
	if len(domains) > 0 {
		dirs[domainRoot] = true
	}
	result := make([]string, 0, len(dirs))
	for dir := range dirs {
		result = append(result, dir)
	}
	sort.Strings(result)
	return result
}
func domainIndex(domains map[string]core.ModelDomain, sources map[string]core.ModelDomainInput, target, projectPath string) []byte {
	var b strings.Builder
	if projectPath == "" {
		projectPath = "markitect.yaml"
	}
	fmt.Fprintf(&b, "<!-- %s; source: %s -->\n# Domain contracts\n\n", marker, projectPath)
	for _, p := range sortedResourcePaths(domains) {
		d := domains[p]
		label := fmt.Sprintf("%s (`%s`)", markdownText(d.Name), markdownCode(d.APIVersion))
		fmt.Fprintf(&b, "- [%s](%s) — source `%s`\n", label, relative(target, p), markdownCode(sources[p].Path))
	}
	return []byte(b.String())
}
